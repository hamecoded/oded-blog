export type PKey = keyof typeof en;

/** `pt('deleteN', { n: 3 })` in the interface language. */
export function usePt() {
  const { prefs } = useApp();
  const dict = prefs.uiLang === 'he' ? he : en;
  return (key: PKey, vars?: Record<string, string | number>) =>
    dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? ''));
}
