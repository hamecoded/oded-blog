/** `tt('nOfM', { n: 3, m: 5 })` in the interface language. */
export function useTt(): Tt {
  const { prefs } = useApp();
  const dict = prefs.uiLang === 'he' ? he : en;
  return (key, vars) => dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? ''));
}
